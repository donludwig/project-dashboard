#!/usr/bin/env python3
"""sync-tasks.py: optional helper that builds the dashboard task cards from ticket files.

The dashboard works without this script (task cards can be written by hand). Use it when your
tasks live in Markdown files: the ticket file stays the source of truth, the dashboard is a view.
Only the block between <!-- AUTO-TASKS:BEGIN ... --> and <!-- AUTO-TASKS:END --> in index.html
is rewritten.

Ticket = Markdown file with YAML frontmatter:

    ---
    id: DEMO-1
    title: "Short task title"
    status: open            # open | active | blocked | waiting -> shown; done | dropped -> skipped
    status_note: ""         # optional: who/what/when behind the status
    priority: high          # high | medium | low
    project: my-app         # anchor id of the project row in the overview table
    due: 2026-12-01         # optional: a date (shown as "in 3 days", "today", "overdue") or a short text ("this week")
    created: 2026-11-09
    summary: "One line for the card"
    next: "The next concrete step"
    dashboard: false        # optional: keep the ticket off the dashboard
    ---
    Free-form notes.

`status` holds one bare value, the context goes into `status_note`; a kanban board grouped by
status (Obsidian Bases, see tasks.base) then gets one clean column per value.

Cards appear in file name order (demo-001-..., demo-002-...). The pill on a card shows `due`,
or `status_note` when there is no `due`, or the status itself.

Usage: python3 sync-tasks.py        (Python standard library only)
"""
import datetime as dt, glob, html, os, re, sys

BASE = os.path.dirname(os.path.abspath(__file__))
DASH = os.path.join(BASE, 'index.html')

# Where your tickets live. Relative globs are resolved against the dashboard folder.
# 'project' is the fallback anchor id when a ticket has no `project:` field.
SOURCES = [
    {'glob': 'tasks/*.md'},
    # {'glob': '~/projects/my-app/tasks/*.md', 'project': 'my-app'},
]

# Frontmatter status -> (data-state, status class, pill variant). The values on the left of the
# tuple are internal keys of the dashboard script and must stay as they are.
SHOWN = {
    'open': ('offen', 'offen', 'info'),
    'active': ('offen', 'offen', 'info'),
    'blocked': ('wartet', 'aktiv', 'warn'),
    'waiting': ('wartet', 'aktiv', 'warn'),
}
PRIO = {'high': 'hoch', 'medium': 'mittel', 'low': 'niedrig'}
FRONTMATTER = re.compile(r'---\n(.*?)\n---\n?', re.S)
BEGIN = '<!-- AUTO-TASKS:BEGIN (generated by sync-tasks.py from tasks/*.md, do not edit by hand) -->'


def parse(path):
    text = open(path, encoding='utf-8').read()
    m = FRONTMATTER.match(text)
    if not m:
        return None
    fm = {}
    for line in m.group(1).splitlines():
        km = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if km:
            v = km.group(2).strip()
            quoted = re.match(r'^(["\'])(.*?)\1', v)
            fm[km.group(1)] = quoted.group(2) if quoted else re.sub(r'\s+#.*$', '', v)  # unquoted: drop trailing comment
    return fm


def projects(page):
    """anchor id -> project name, read from the overview table so nothing is configured twice."""
    out = {}
    for m in re.finditer(r'<a class="table-name[^"]*" href="#([^"]+)">(.*?)</a>', page, re.S):
        name = re.sub(r'<[^>]+>', '', m.group(2)).strip()
        out.setdefault(m.group(1), html.unescape(name))
    return out


def due_text(fm, today):
    due = fm.get('due') or fm.get('deadline') or ''
    if re.fullmatch(r'\d{4}-\d{2}-\d{2}', due):
        days = (dt.date.fromisoformat(due) - today).days
        return 'overdue' if days < 0 else 'today' if days == 0 else 'tomorrow' if days == 1 else f'in {days} days'
    return due or fm.get('status_note') or fm['status']


def card(fm, known, today):
    e = html.escape
    state, cls, pill = SHOWN[fm['status']]
    pid = fm.get('project', '')
    title = fm.get('title', '')
    meta = f'<a href="#{e(pid)}" class="proj-link km-link km-link--projekt">{e(known.get(pid, pid))}</a>' if pid else ''
    return f'''
      <div class="task-item km-task" data-generated="1" data-state="{state}" data-prio="{PRIO.get(fm.get('priority'), 'mittel')}">
        <input type="checkbox" class="task-checkbox km-task__check" aria-label="Done: {e(title)}">
        <div class="task-content km-task__body">
          <div class="task-title km-task__title"><span>{e(title)}</span><span class="task-id km-task__id">{e(fm.get('id', ''))}</span><span class="task-status {cls} km-pill km-pill--{pill}">{e(due_text(fm, today))}</span></div>
          <p class="km-task__text">{e(fm.get('summary', ''))}</p>
          <p class="km-task__next"><strong>Next step:</strong> {e(fm.get('next', ''))}</p>
          <div class="task-meta km-task__meta">{meta}</div>
        </div>
      </div>'''


def main():
    page = open(DASH, encoding='utf-8').read()
    pat = re.compile(r'<!-- AUTO-TASKS:BEGIN.*?-->(.*?)<!-- AUTO-TASKS:END -->', re.S)
    if not pat.search(page):
        sys.exit('ERROR: AUTO-TASKS markers are missing in index.html')
    known, today, cards = projects(page), dt.date.today(), []
    for src in SOURCES:
        pattern = os.path.expanduser(src['glob'])
        for path in sorted(glob.glob(pattern if os.path.isabs(pattern) else os.path.join(BASE, pattern))):
            if os.path.basename(path).startswith(('README', '_')):
                continue
            fm = parse(path)
            if not fm or not fm.get('status'):
                continue
            fm['status'] = fm['status'].split()[0]
            if fm['status'] not in SHOWN or fm.get('dashboard', '').lower() == 'false':
                continue
            fm.setdefault('project', src.get('project', ''))
            cards.append(card(fm, known, today))
    block = BEGIN + ''.join(cards) + '\n<!-- AUTO-TASKS:END -->'
    open(DASH, 'w', encoding='utf-8').write(pat.sub(lambda _: block, page, count=1))
    print(f'{len(cards)} task cards generated.')


if __name__ == '__main__':
    main()
